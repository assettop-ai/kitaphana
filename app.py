@app.route("/loans/add", methods=["GET", "POST"])
def add_loan():
    if not is_librarian():
        return "Бұл бөлімге тек кітапханашы кіре алады", 403
    db = get_db()

    readers = db.execute("""
        SELECT *
        FROM okuyandar
        ORDER BY aty
    """).fetchall()

    books = db.execute("""
        SELECT *
        FROM kitaptar
        ORDER BY ataui
    """).fetchall()

    if request.method == "POST":

        okuyman_id = request.form["okuyman_id"]
        kitap_id = request.form["kitap_id"]
        merzim = request.form["merzim"]

        if DATABASE_URL:
            db.execute("""
                INSERT INTO kitap_beru
                (
                    kuni,
                    okuyman_id,
                    kitap_id,
                    berildi,
                    kaitaryldy,
                    kaitaru_kuni,
                    merzim
                )
                VALUES
                (
                    %s,
                    %s,
                    %s,
                    'Иә',
                    'Жоқ',
                    '',
                    %s
                )
            """, (
                date.today().isoformat(),
                okuyman_id,
                kitap_id,
                merzim
            ))

        else:
            db.execute("""
                INSERT INTO kitap_beru
                (
                    kuni,
                    okuyman_id,
                    kitap_id,
                    berildi,
                    kaitaryldy,
                    kaitaru_kuni,
                    merzim
                )
                VALUES
                (
                    ?,
                    ?,
                    ?,
                    'Иә',
                    'Жоқ',
                    '',
                    ?
                )
            """, (
                date.today().isoformat(),
                okuyman_id,
                kitap_id,
                merzim
            ))

        db.commit()
        db.close()

        return redirect(url_for("loans"))

    db.close()

    return render_template_string("""
    <h2>Кітап беру</h2>

    <form method="post">

        <label>Оқырман:</label>
        <select name="okuyman_id" required>
            {% for reader in readers %}
                <option value="{{ reader.id }}">
                    {{ reader.aty }} — {{ reader.synyp }}
                </option>
            {% endfor %}
        </select>

        <br><br>

        <label>Кітап:</label>
        <select name="kitap_id" required>
            {% for book in books %}
                <option value="{{ book.id }}">
                    {{ book.ataui }}
                </option>
            {% endfor %}
        </select>

        <br><br>

        <label>Мерзімі:</label>
        <input type="date" name="merzim" required>

        <br><br>

        <button type="submit">Кітап беру</button>

    </form>
    """, readers=readers, books=books)
