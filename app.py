DB_NAME = "kitaphana.db"

DATABASE_URL = os.environ.get("DATABASE_URL")

def get_db():
    if DATABASE_URL:
        import psycopg
        from psycopg.rows import dict_row
        return psycopg.connect(
            DATABASE_URL,
            row_factory=dict_row
        )
    db = sqlite3.connect(DB_NAME)
    db.row_factory = sqlite3.Row
    return db

def init_db():
    db = get_db()
    if DATABASE_URL:
        id_type = "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    else:
        id_type = "INTEGER PRIMARY KEY AUTOINCREMENT"
    
    # ОҚЫРМАНДАР
    db.execute(f"""
        CREATE TABLE IF NOT EXISTS okuyandar (
            id {id_type},
            aty TEXT NOT NULL,
            synyp TEXT,
            turi TEXT,
            tirkelgen_kuni DATE
        )
    """)
    if DATABASE_URL:
        db.execute("""
            ALTER TABLE okuyandar
            ADD COLUMN IF NOT EXISTS tirkelgen_kuni DATE
        """)
    else:
        columns = [
            row["name"]
            for row in db.execute("PRAGMA table_info(okuyandar)").fetchall()
        ]
        if "tirkelgen_kuni" not in columns:
            db.execute("""
                ALTER TABLE okuyandar
                ADD COLUMN tirkelgen_kuni TEXT
            """)
    db.execute("""
        UPDATE okuyandar
        SET tirkelgen_kuni = '2026-09-01'
        WHERE tirkelgen_kuni IS NULL
    """)
    
    # КІТАПТАР
    db.execute(f"""
        CREATE TABLE IF NOT EXISTS kitaptar (
            id {id_type},
            kitap_id TEXT NOT NULL UNIQUE,
            ataui TEXT NOT NULL,
            avtor TEXT,
            sanat TEXT,
            jalpy_sany INTEGER DEFAULT 0
        )
    """)
    
    # КІТАП БЕРУ
    db.execute(f"""
        CREATE TABLE IF NOT EXISTS kitap_beru (
            id {id_type},
            kuni TEXT NOT NULL,
            okuyman_id INTEGER NOT NULL,
            kitap_id INTEGER NOT NULL,
            berildi TEXT DEFAULT 'Иә',
            kaitaryldy TEXT DEFAULT 'Жоқ',
            kaitaru_kuni TEXT,
            merzim TEXT
        )
    """)
    if DATABASE_URL:
        db.execute("""
            ALTER TABLE kitaptar
            ADD COLUMN IF NOT EXISTS baspa TEXT
        """)
        db.execute("""
            ALTER TABLE kitaptar
            ADD COLUMN IF NOT EXISTS zhyl TEXT
        """)
    else:
        columns = {
            row["name"]
            for row in db.execute(
                "PRAGMA table_info(kitaptar)"
            ).fetchall()
        }
        if "baspa" not in columns:
            db.execute(
                "ALTER TABLE kitaptar ADD COLUMN baspa TEXT"
            )
        if "zhyl" not in columns:
            db.execute(
                "ALTER TABLE kitaptar ADD COLUMN zhyl TEXT"
            )
    db.commit()

    # personal.xlsx ФАЙЛЫНАН МӘЛІМЕТТЕРДІ АВТОМАТТЫ ТҮРДЕ ЖҮКТЕУ (нөмірлерді алып тастау)
    teachers_file = "personal.xlsx"
    if os.path.exists(teachers_file):
        db.execute("DELETE FROM okuyandar")
        db.commit()

        df_t = pd.read_excel(teachers_file)
        for _, row in df_t.iterrows():
            raw_aty = str(row.get('Аты-жөні') or '').strip()
            # Басындағы реттік нөмірді (мысалы, "151. " немесе "151) ") тазарту
            aty = re.sub(r'^\d+[\.\)]\s*', '', raw_aty).strip()
            synyp = str(row.get('Сыныбы/пәні') or '').strip()
            
            if not aty or aty.lower() == 'nan':
                continue

            # 0-сынып немесе даярлық топтарын өткізіп жіберу
            if synyp.startswith('0') or synyp == '0' or 'даярлық' in synyp.lower():
                continue

            # Мұғалім немесе оқушы екенін анықтау
            is_teacher = False
            if any(char.isalpha() for char in synyp) and not re.match(r'^\d+[\s\-]*[а-яәғқңөұүһі]*$', synyp.lower()):
                is_teacher = True
            
            if is_teacher:
                turi = "Мұғалім"
                synyp = "/мұғалім"
            else:
                turi = "Оқушы"

            if DATABASE_URL:
                db.execute("""
                    INSERT INTO okuyandar (aty, synyp, turi, tirkelgen_kuni)
                    VALUES (%s, %s, %s, %s)
                """, (aty, synyp, turi, '2026-09-01'))
            else:
                db.execute("""
                    INSERT INTO okuyandar (aty, synyp, turi, tirkelgen_kuni)
                    VALUES (?, ?, ?, ?)
                """, (aty, synyp, turi, '2026-09-01'))
        db.commit()

    db.close()

